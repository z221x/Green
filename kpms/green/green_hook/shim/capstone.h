#define CS_MODE_BIG_ENDIAN 0x80000000
#define CS_MODE_ARM 0x01
#define CS_MODE_V8 0x80
#define CS_MODE_32 0
#define CS_MODE_64 0
#define CS_MODE_MIPS32 0
#define CS_MODE_MIPS64 0

typedef enum cs_arch
{
  CS_ARCH_ARM64 = 0,
  CS_ARCH_X86,
  CS_ARCH_MIPS,
} cs_arch;

