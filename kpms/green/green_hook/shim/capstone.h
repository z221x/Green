/*
 * Minimal capstone shim for the vendored frida-gum sources.
 *
 * gumarm64writer uses capstone only for the arm64 register enum and
 * condition-code enum (no disassembly), so this shim reproduces the capstone
 * ARM64 register numbering.  The numbering only needs internal consistency
 * for the writer's register describe/switch logic.
 *
 * gumarm64reader needs a real disassembler (cs_disasm_iter) and is therefore
 * not part of the green_hook build yet.
 */

